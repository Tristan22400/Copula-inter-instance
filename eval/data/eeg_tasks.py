"""EEG joint-prediction tasks of two neural-process benchmarks, as batches of tabular episodes.

Raw data come from scripts/npbench/export_eeg.py (the benchmark's own `neuralprocesses` code, run
in its own venv). Each task is one episode: context rows (x, y) and target rows (x, y), with the 7
electrodes of a trial stacked as rows. A row's features are [time (s), one-hot electrode (7)], so a
scalar-output tabular model scores the 7-channel trial as one table.

Two task families:

- "arcnp_<mode>" (Bruinsma et al., ICLR 2023, exact): the paper's evaluation batches, regenerated by
  its own EEGGenerator (subject split seed 99, 10 evaluation subjects, generator seed 0, 16 tasks per
  batch sharing one context/target split, 2^12 tasks). Raw microvolts. mode: interpolation (per
  electrode, U{50..256} random targets) or reconstruction (one electrode cut at t0 ~ U[0.5, 0.75] s,
  the other six fully observed).
- "hassan_<int|for>" (Hassan et al., ICLR 2026, reconstructed from the paper's text; their code is
  not released): every evaluation trial, standardised per electrode, with N context time points
  (all 7 electrodes) and M target time points (all 7 electrodes). int: N + M distinct random time
  points; for: the first N time points as context and the next M as targets. The standardisation
  statistics are not given in the paper; we use the per-electrode mean/std over the training
  subjects' trials (Bruinsma's split).

Scores are per target scalar (nps.num_data's normalisation): log q(y_T | ctx) / |T|.
"""

from __future__ import annotations

import json
import os
import zlib
from collections.abc import Iterator, Sequence
from dataclasses import dataclass

import numpy as np

N_ELECTRODES = 7
ARCNP_MODES = ("interpolation", "reconstruction")
HASSAN_MODES = ("int", "for")

__all__ = [
    "ARCNP_MODES",
    "HASSAN_MODES",
    "N_ELECTRODES",
    "EEGBatch",
    "arcnp_batches",
    "arcnp_n_batches",
    "eeg_trials",
    "featurize",
    "hassan_batches",
    "n_eval_trials",
    "spread",
    "task_names",
]


@dataclass
class EEGBatch:
    """B episodes sharing their row counts: context (B, P, d) / (B, P), targets (B, N, d) / (B, N)."""

    x_train: np.ndarray
    y_train: np.ndarray
    x_test: np.ndarray
    y_test: np.ndarray
    # Global indices of the batch's episodes in its task (for seeding and bookkeeping).
    index: np.ndarray
    # Context size label of the batch (Hassan: N time points; ARCNP: context rows).
    n_context: int


def task_names() -> list[str]:
    """Every task name the runner accepts."""
    return [f"arcnp_{m}" for m in ARCNP_MODES] + [f"hassan_{m}" for m in HASSAN_MODES]


def featurize(t: np.ndarray, electrode: np.ndarray) -> np.ndarray:
    """(..., n) times and (n,) or (..., n) electrode indices -> (..., n, 1 + 7) features [t, one-hot]."""
    t = np.asarray(t, dtype=np.float64)
    onehot = np.eye(N_ELECTRODES)[np.broadcast_to(np.asarray(electrode, dtype=np.int64), t.shape)]
    return np.concatenate([t[..., None], onehot], axis=-1)


def spread(n_total: int, k: int) -> np.ndarray:
    """k (or fewer, if n_total < k) distinct indices evenly spaced over 0..n_total-1, first and last included."""
    if k <= 0 or n_total <= 0:
        return np.zeros(0, dtype=np.int64)
    return np.unique(np.rint(np.linspace(0, n_total - 1, min(k, n_total))).astype(np.int64))


def arcnp_n_batches(data_dir: str, mode: str) -> int:
    """Number of batches in the exported evaluation set of mode."""
    with np.load(os.path.join(data_dir, f"eeg_arcnp_{mode}.npz")) as f:
        return int(json.loads(str(f["meta"]))["n_batches"])


def n_eval_trials(data_dir: str) -> int:
    """Number of evaluation trials (the 10 evaluation subjects')."""
    with np.load(os.path.join(data_dir, "eeg_trials.npz")) as f:
        return int(f["y"].shape[0])


def arcnp_batches(data_dir: str, mode: str, max_batches: int | None = None) -> Iterator[EEGBatch]:
    """The paper's evaluation batches for mode (interpolation / reconstruction), in generator order."""
    if mode not in ARCNP_MODES:
        raise ValueError(f"mode={mode!r} is not one of {ARCNP_MODES}")
    path = os.path.join(data_dir, f"eeg_arcnp_{mode}.npz")
    with np.load(path) as f:
        meta = json.loads(str(f["meta"]))
        n = int(meta["n_batches"]) if max_batches is None else min(int(meta["n_batches"]), max_batches)
        start = 0
        for i in range(n):
            xc, oc, yc = f[f"b{i}_xc"], f[f"b{i}_oc"], f[f"b{i}_yc"]
            xt, ot, yt = f[f"b{i}_xt"], f[f"b{i}_ot"], f[f"b{i}_yt"]
            if np.isnan(yc).any() or np.isnan(yt).any():
                raise ValueError(f"{path} batch {i}: NaN outputs (unexpected for EEG)")
            B = yc.shape[0]
            yield EEGBatch(
                x_train=featurize(xc[..., 0], oc),
                y_train=yc.astype(np.float64),
                x_test=featurize(xt[..., 0], ot),
                y_test=yt.astype(np.float64),
                index=np.arange(start, start + B),
                n_context=int(yc.shape[1]),
            )
            start += B


def eeg_trials(data_dir: str) -> dict[str, np.ndarray]:
    """The evaluation subjects' trials: y (T, 256, 7) raw, x (256,), train_mean / train_std (7,)."""
    with np.load(os.path.join(data_dir, "eeg_trials.npz")) as f:
        return {k: f[k] for k in ("y", "x", "train_mean", "train_std")}


def _split(rng: np.random.Generator, mode: str, n_time: int, n_context: int, n_target: int) -> tuple:
    if n_context + n_target > n_time:
        raise ValueError(f"N + M = {n_context + n_target} exceeds the {n_time} time points")
    if mode == "int":
        perm = rng.permutation(n_time)
        return np.sort(perm[:n_context]), np.sort(perm[n_context : n_context + n_target])
    return np.arange(n_context), np.arange(n_context, n_context + n_target)


def hassan_batches(
    data_dir: str,
    mode: str,
    n_context: int,
    n_target: int,
    *,
    batch_size: int,
    seed: int,
    max_trials: int | None = None,
    trials: Sequence[int] | None = None,
) -> Iterator[EEGBatch]:
    """Hassan et al.'s EEG task over the evaluation trials, standardised, batch_size trials per batch.

    trials selects a subset (global trial indices); default every trial (up to max_trials). The
    context/target time points of trial j are drawn from default_rng(crc32(seed, mode, N, M, j)),
    so a task is the same whatever the batching or the trial subset.
    """
    if mode not in HASSAN_MODES:
        raise ValueError(f"mode={mode!r} is not one of {HASSAN_MODES}")
    tr = eeg_trials(data_dir)
    y = (tr["y"] - tr["train_mean"]) / tr["train_std"]  # (T, 256, 7)
    T, n_time, n_el = y.shape
    if max_trials is not None:
        T = min(T, max_trials)
    order = np.arange(T) if trials is None else np.asarray(trials, dtype=np.int64)
    if order.size and (order.min() < 0 or order.max() >= T):
        raise ValueError(f"trial indices must lie in [0, {T})")
    rows_t = np.repeat(np.arange(n_time), n_el)  # time index of each stacked row
    rows_e = np.tile(np.arange(n_el), n_time)  # electrode of each stacked row
    for s in range(0, len(order), batch_size):
        js = order[s : s + batch_size]
        xc, yc, xq, yq = [], [], [], []
        for j in js:
            key = zlib.crc32(f"hassan-eeg:{seed}:{mode}:{n_context}:{n_target}:{j}".encode())
            ctx_t, tgt_t = _split(np.random.default_rng(key), mode, n_time, n_context, n_target)
            ctx = np.isin(rows_t, ctx_t)
            tgt = np.isin(rows_t, tgt_t)
            xc.append(featurize(tr["x"][rows_t[ctx]], rows_e[ctx]))
            yc.append(y[j, rows_t[ctx], rows_e[ctx]])
            xq.append(featurize(tr["x"][rows_t[tgt]], rows_e[tgt]))
            yq.append(y[j, rows_t[tgt], rows_e[tgt]])
        yield EEGBatch(
            x_train=np.stack(xc),
            y_train=np.stack(yc),
            x_test=np.stack(xq),
            y_test=np.stack(yq),
            index=js,
            n_context=n_context,
        )
